"""Writes igc_binding_tokens.hpp: the pack's tokens that tie what follows them to something before the expression."""
import argparse
from pathlib import Path
from tools.qwenputer.tokenizer import NativeText

SIGNS = '+-*/^×÷·−–—∙⋅'
CLOSERS = ')]}'
WORDS = {'times', 'cdot', 'div', 'plus', 'minus', 'x', 'X', 'by', 'over', 'pm', 'mp', 'ast'}


def binds(text):
    """`=-`, `)*`, ` times`: the number after it is not the start of a whole expression. `**` is the caller's: it is also bold."""
    tail = text.rstrip(' ')
    if not tail or text.strip() in WORDS:
        return bool(tail)
    if len(set(tail.strip())) == 1 and len(tail.strip()) > 1 and tail.strip()[0] in '*-':
        return False  # markdown rules and bold
    return tail[-1] in SIGNS or tail[-1] in CLOSERS


def ids(tokenizer, size):
    found = []
    for token in range(size):
        try:
            if binds(tokenizer.decode_bytes([token]).decode('utf-8')):
                found.append(token)
        except UnicodeDecodeError:
            pass
    return found


def header(found):
    rows = [', '.join(str(t) for t in found[i:i+14]) for i in range(0, len(found), 14)]
    body = ',\n    '.join(rows)
    return ('#pragma once\n// Generated by tools/igc/binding_tokens.py from the Gyro-M pack; sorted.\n#include <algorithm>\n#include <cstdint>\n#include <iterator>\n\n'
            'namespace strata::igc {\ninline constexpr int32_t kBindingTokens[] = {\n    ' + body + '\n};\n'
            'inline bool binds_next(int32_t token) {\n    return std::binary_search(std::begin(kBindingTokens), std::end(kBindingTokens), token);\n}\n}\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--pack', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=Path('include/strata/core/igc_binding_tokens.hpp'))
    parser.add_argument('--size', type=int, default=248100)
    args = parser.parse_args()
    found = ids(NativeText.from_pack(args.pack / 'tokenizer'), args.size)
    args.output.write_text(header(found), encoding='utf-8', newline='\n')
    print(len(found))
