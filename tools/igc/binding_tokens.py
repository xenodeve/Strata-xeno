"""Writes igc_binding_tokens.hpp: the pack's tokens that tie what follows them to something before the expression, and
those a number written against them is still a number after (`d12^2=`, `sin60^3=`, `a1 +1 =` are names, not numbers)."""
import argparse
from pathlib import Path
from tools.qwenputer.tokenizer import NativeText

SIGNS = '+-*/^×÷·−–—∙⋅√∛∜'
CLOSERS = ')]}'
WORDS = {'times', 'cdot', 'div', 'plus', 'minus', 'x', 'X', 'by', 'over', 'pm', 'mp', 'ast'}


def binds(text):
    """`=-`, `)*`, ` times`: the number after it is not the start of a whole expression. `**` is the caller's: it is also bold."""
    tail = text.rstrip(' ')
    if not tail or text.strip() in WORDS:
        return bool(tail)
    if len(set(tail.strip())) == 1 and len(tail.strip()) > 1 and tail.strip()[0] in '*-':
        return False  # markdown rules and bold
    return tail[-1] in SIGNS or tail[-1] in CLOSERS


def starts_clean(text):
    return bool(text) and not (text[-1].isalnum() or text[-1] == '_')


def ids(tokenizer, size, keep):
    found = []
    for token in range(size):
        try:
            if keep(tokenizer.decode_bytes([token]).decode('utf-8')):
                found.append(token)
        except UnicodeDecodeError:
            pass
    return found


def table(name, found):
    rows = [', '.join(str(t) for t in found[i:i+14]) for i in range(0, len(found), 14)]
    return f'inline constexpr int32_t {name}[] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


def search(function, name):
    return f'inline bool {function}(int32_t token) {{\n    return std::binary_search(std::begin({name}), std::end({name}), token);\n}}\n'


def header(binding, clean):
    return ('#pragma once\n// Generated by tools/igc/binding_tokens.py from the Gyro-M pack; sorted.\n#include <algorithm>\n'
            '#include <cstdint>\n#include <iterator>\n\nnamespace strata::igc {\n'
            + table('kBindingTokens', binding) + table('kCleanBefore', clean)
            + search('binds_next', 'kBindingTokens') + search('number_may_follow', 'kCleanBefore') + '}\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--pack', type=Path, required=True)
    parser.add_argument('--output', type=Path, default=Path('include/strata/core/igc_binding_tokens.hpp'))
    parser.add_argument('--size', type=int, default=248100)
    args = parser.parse_args()
    tokenizer = NativeText.from_pack(args.pack / 'tokenizer')
    binding, clean = ids(tokenizer, args.size, binds), ids(tokenizer, args.size, starts_clean)
    args.output.write_text(header(binding, clean), encoding='utf-8', newline='\n')
    print(len(binding), len(clean))
